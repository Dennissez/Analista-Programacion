CREATE TABLE DETALLE_BOLETA
(nro_boleta     NUMBER (10) NOT NULL ,
 cod_producto   NUMBER (8) NOT NULL ,
 cantidad       NUMBER (5) NOT NULL ,
 valor_unitario NUMBER (5) NOT NULL ,
 valor_total    NUMBER (8) NOT NULL) ;
ALTER TABLE DETALLE_BOLETA ADD CONSTRAINT PK_DETALLE_FACTURA PRIMARY KEY(nro_boleta, cod_producto);


CREATE TABLE PRODUCTO
(cod_producto  NUMBER (8) NOT NULL ,
 desc_producto VARCHAR2 (40) NOT NULL,
 stock_minimo  NUMBER (5) NOT NULL ,
 stock_actual  NUMBER (5) NOT NULL) ;
ALTER TABLE PRODUCTO ADD CONSTRAINT PK_PRODUCTO PRIMARY KEY(cod_producto);


CREATE TABLE VENDEDOR
(cod_vendedor     NUMBER (5) NOT NULL ,
 numrut_vendedor  NUMBER (10) NOT NULL ,
 dvrut_vendedor   VARCHAR2 (1) NOT NULL ,
 pnombre_vendedor VARCHAR2 (25) NOT NULL ,
 snombre_vendedor VARCHAR2 (25) ,
 appat_vendedor   VARCHAR2 (25) NOT NULL ,
 apmat_vendedor   VARCHAR2 (25) NOT NULL ,
 fecha_contrato   DATE NOT NULL ,
 porc_comision    NUMBER(3,1),
 sueldo_base      NUMBER (8) NOT NULL) ;
ALTER TABLE VENDEDOR ADD CONSTRAINT PK_VENDEDOR PRIMARY KEY(cod_vendedor);
ALTER TABLE BOLETA ADD CONSTRAINT FK_BOLETA_CLIENTE FOREIGN KEY(cod_cliente) REFERENCES CLIENTE(cod_cliente);
ALTER TABLE BOLETA ADD CONSTRAINT FK_BOLETA_VENDEDOR FOREIGN KEY(id_vendedor) REFERENCES VENDEDOR (cod_vendedor);
ALTER TABLE DETALLE_BOLETA ADD CONSTRAINT FK_DETALLE_BOLETA_BOLETA FOREIGN KEY(nro_boleta) REFERENCES BOLETA(nro_boleta);
ALTER TABLE DETALLE_BOLETA ADD CONSTRAINT FK_DETALLE_BOLETA_PRODUCTO FOREIGN KEY (cod_producto) REFERENCES PRODUCTO (cod_producto);



