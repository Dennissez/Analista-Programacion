CREATE TABLE BOLETA
(nro_boleta   NUMBER (10) NOT NULL ,
 fecha_boleta DATE NOT NULL ,
 monto_boleta NUMBER (10) NOT NULL ,
 id_vendedor  NUMBER (5) NOT NULL ,
 cod_cliente  NUMBER (5) NOT NULL);
ALTER TABLE BOLETA ADD CONSTRAINT PK_BOLETA PRIMARY KEY(nro_boleta);


CREATE TABLE CLIENTE
(cod_cliente         NUMBER (5) NOT NULL ,
 numrut_cliente      NUMBER (10) NOT NULL ,
