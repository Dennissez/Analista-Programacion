-- EJERCICIO 2
SELECT numrut_vendedor||'-'||dvrut_vendedor AS VENDEDOR, -- CONCATENAMOS EL RUT CON EL DÍGITO VERIFICADOR 
                                                         -- CON EL ALIAS VENDEDOR
fecha_contrato AS CONTRATADO -- SELECCIONAMOS LA FECHA DE CONTRATO CON EL ALIAS CONTRATADO
FROM VENDEDOR -- DESDE LA TABLA VENDEDOR
WHERE porc_comision IS NULL -- DONDE LA CONDICIÓN ES QUE EL PORCENTAJE DE COMISIÓN SEA NULO
ORDER BY fecha_contrato ASC; -- ORDENADOS POR FECHA DE CONTRATO DE FORMA ASCENDENTE

-- EJERCICIO 3
SELECT cod_vendedor AS CODIGO, -- SELECCIONAMOS EL COD_VENDEDOR CON EL ALIAS CODIGO
pnombre_vendedor||' '||appat_vendedor AS "NOMBRE VENDEDOR", -- CONCATENAMOS NOMBRE Y APELLIDO SEPARADOS POR 
                                                            -- UN ESPACIO, CON EL ALIAS NOMBRE VENDEDOR
sueldo_base AS "SUELDO BASE", -- SELECCIONAMOS EL SUELDO_BASE CON EL ALIAS SUELDO BASE
(sueldo_base * 0.066) AS BONO -- OBTENEMOS EL 6,6% DEL SUELDO CON EL ALIAS BONO
FROM VENDEDOR -- DESDE LA TABLA VENDEDOR
WHERE sueldo_base < 200000; -- LA CONDICIÓN ES QUE EL SUELDO_BASE SEA MENOR A 200000 

-- EJERCICIO 4
SELECT numrut_vendedor ||'-'||dvrut_vendedor AS "RUT VENDEDOR", -- CONCATENAMOS EL RUT CON SU DÍGITO VERIFICADOR
                                                                -- CON EL ALIAS RUT VENDEDOR
pnombre_vendedor||' '||appat_vendedor AS "NOMBRE VENDEDOR", -- CONCATENAMOS NOMBRE Y APELLIDO CON EL ALIAS
                                                            -- NOMBRE VENDEDOR
fecha_contrato AS "FECHA CONTRATO", --SELECCIONAMOS LA FECHA_CONTRATO CON EL ALIAS FECHA CONTRATO
sueldo_base AS "SUELDO BASE" -- SELECCIONAMOS SUELDO_BASE CON EL ALIAS SUELDO BASE
FROM VENDEDOR -- DESDE LA TABLA VENDEDOR
WHERE fecha_contrato BETWEEN '01/01/2001' AND '31/01/2001' -- DONDE LA CONDICIÓN ES QUE LA FECHA DE CONTRATO
                                                           -- ESTÉ ENTRE EL 01 DE ENERO DE 2001 Y 31 DE ENERO 
                                                           -- DEL MISMO AÑO (MES DE ENERO 2001)
OR  fecha_contrato BETWEEN '01/07/2013' AND '31/07/2013'   -- O LA FECHA DE CONTRATO ESTÉ ENTRE EL 01 DE JULIO
                                                           -- DEL AÑO 2013 (MES DE JULIO DE 2013)
ORDER BY fecha_contrato ASC; -- ORDENADO ASCENDENTEMENTE POR FECHA DE CONTRATO

