/* SELECCIONAMOS EL LITERAL 'EL CÓDIGO DEL PRODUCTO ' CONCATENADO CON EL COD_PRODUCTO, LUEGO CON EL 
LITERAL ' QUE CORRESPONDE A ' Y CONCATENAMOS CON LA DESCRIPCIÓN DEL PRODUCTO Y POR ÚLTIMO, CONCATENADO CON
EL LITERAL ' POSEE UNA LETRA E COMO PENÚLTIMO CARACTER ' CON EL ALIAS LISTA DE PRODUCTOS */
SELECT 'El código de producto '||cod_producto||' que corresponde a '||desc_producto||
' posee una letra E como penúltimo caracter' AS "LISTADO DE PRODUCTOS"
FROM PRODUCTO -- DESDE LA TABLA PRODUCTO
WHERE desc_producto LIKE '%E_'; -- DONDE LA CONDICIÓN ES QUE LA DESCRIPCIÓN DEL PRODUCTO TENGA COMO
                                -- PENÚLTIMA LETRA UNA 'E' (PATRÓN DE BÚSQUEDA CONSTRUIDO CON LIKE)

-- EJERCICIO 6
SELECT pnombre_vendedor||' '||appat_vendedor AS VENDEDOR, -- CONCATENAMOS NOMBRE Y APELLIDO CON EL ALIAS VENDEDOR
sueldo_base AS "SUELDO BASE" -- SELECCIONAMOS SUELDO_BASE CON EL ALIAS SUELDO BASE
FROM VENDEDOR -- DESDE LA TABLA VENDEDOR
WHERE sueldo_base BETWEEN 180000 AND 250000 -- DONDE LA CONDICIÓN ES QUE EL SUELDO BASE ESTÉ ENTRE 180000 Y 25000
                                            -- (AMBOS VALORES INCLUIDOS)
AND porc_comision IS NOT NULL; -- Y QUE EL PORCENTAJE DE COMISIÓN NO ESTÉ NULO (ES DECIR, TENGA UN VALOR ASOCIADO)

-- EJERCICIO 7
SELECT cod_vendedor AS "CODIGO VENDEDOR", -- SELECCIONAMOS COD_VENDEDOR CON EL ALIAS CODIGO VENDEDOR
sueldo_base AS "SUELDO_BASE", -- SELECCIONAMOS SUELDO_BASE CON EL ALIAS SUELDO_BASE
(204860 - sueldo_base) AS AUMENTO -- RESTAMOS EL SUELDO BASE PROMEDIO AL SUELDO BASE PARA OBTENER EL AUMENTO
FROM VENDEDOR -- DESDE LA TABLA VENDEDOR
WHERE sueldo_base < 204860 -- DONDE LA CONDICIÓN ES QUE EL SUELDO BASE SEA MENOR QUE EL PROMEDIO
ORDER BY sueldo_base DESC; -- ORDENADOS POR SUELDO DESCENDENTEMENTE